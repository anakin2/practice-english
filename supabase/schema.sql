-- Run this file in Supabase Dashboard > SQL Editor as the project owner.
-- No credentials or administrator accounts are embedded in this file.
begin;

create table if not exists public.words (
  id bigint generated by default as identity primary key,
  word text not null unique check (length(trim(word)) between 1 and 100),
  ipa text not null check (length(trim(ipa)) between 1 and 200),
  meaning text not null check (length(trim(meaning)) between 1 and 1000),
  category text not null check (length(trim(category)) between 1 and 100),
  created_at timestamptz not null default now()
);

alter table public.words enable row level security;
revoke all on table public.words from anon, authenticated;
grant usage on schema public to anon, authenticated;
grant select on table public.words to anon, authenticated;
grant insert, update, delete on table public.words to authenticated;
grant usage, select on sequence public.words_id_seq to authenticated;

drop policy if exists "Anyone can read words" on public.words;
create policy "Anyone can read words" on public.words
  for select to anon, authenticated using (true);

-- app_metadata is server-controlled. Never use user_metadata for authorization.
-- No users receive this role by running this script.
drop policy if exists "Word admins can insert" on public.words;
create policy "Word admins can insert" on public.words
  for insert to authenticated
  with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'word_admin');
drop policy if exists "Word admins can update" on public.words;
create policy "Word admins can update" on public.words
  for update to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'word_admin')
  with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'word_admin');
drop policy if exists "Word admins can delete" on public.words;
create policy "Word admins can delete" on public.words
  for delete to authenticated
  using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'word_admin');
commit;
